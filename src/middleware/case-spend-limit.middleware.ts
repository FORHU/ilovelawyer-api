import { Request, Response, NextFunction } from "express";
import CaseLimitsSvc from "../services/case-limits.service";
import { consultationCaseOf } from "./guest-case-items.middleware";
import { workspaceOf } from "../utils/workspace";

const CASE_PATH = /^\/([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})(\/.*)?$/i;

/** What stays open on a case that has used its AI: removing things, renaming it, archiving it,
 * managing who can see it. Everything else that writes can start AI work (an upload re-runs the
 * analysis), so it stops. */
const STILL_OPEN = /^\/(?:opened|archive|unarchive|access|permissions|shares?|invites?|members?)(?:\/|$)/i;

/** GETs that run AI: the case brief is generated by a GET. */
const AI_READ = /^\/export$/;

/** Whether a request to a path under a case is held back once the case has used its AI. `rest` is the
 * path after the case id ("" for the case itself). */
export function startsAiWork(method: string, rest: string): boolean {
  const m = method.toUpperCase();
  if (m === "DELETE" || m === "OPTIONS") return false;
  if (m === "GET" || m === "HEAD") return AI_READ.test(rest);
  if (rest === "" || rest === "/") return false; // editing the case's own details
  return !STILL_OPEN.test(rest);
}

/** Mounted on the case router: once a case has used its AI (CASE_SPEND_LIMIT_USD), writes that could
 * start AI work answer 403 CASE_BUDGET_SPENT; reads, deletes and housekeeping still pass. */
export async function caseSpendLimit(req: Request, _res: Response, next: NextFunction) {
  try {
    const match = CASE_PATH.exec(req.path);
    if (!match || !startsAiWork(req.method, match[2] ?? "")) return next();
    await CaseLimitsSvc.assertCaseHasBudget(match[1]);
    next();
  } catch (err) {
    next(err);
  }
}

/** The same for sending a chat message: a consultation on a case spends that case's AI. A
 * consultation on no case has no case budget. */
export async function consultationSpendLimit(req: Request, _res: Response, next: NextFunction) {
  try {
    const consultation = await consultationCaseOf(req.params.consultationId, workspaceOf(req));
    if (consultation?.caseId) await CaseLimitsSvc.assertCaseHasBudget(consultation.caseId);
    next();
  } catch (err) {
    next(err);
  }
}
