import { Request, Response, NextFunction } from "express";
import jwt from "jsonwebtoken";
import AuthRepo from "../repositories/auth.repository";
import LlmUsageSvc from "../services/llm-usage.service";
import HttpError from "../utils/http-error";
import { ACCESS_TOKEN_SECRET } from "../config";

/** Still open to an account whose credit is spent: signing in and out, and the account itself
 * (profile, password, deletion, data export, consents), which must never be locked behind a
 * payment. Everything else that is not a read is new work. */
const ALWAYS_OPEN = /^\/api(?:\/v1)?\/(?:auth|users\/me|consents)(?:\/|$)/;

/** The client app pays per case and counts chat credits per case (ClientBillingSvc), which take
 * the place of the account-wide free credit there. Without this a client who had used it up
 * couldn't even pay for a case. */
const CLIENT_APP = /^\/api(?:\/v1)?\/client(?:\/|$)/;

/** GETs that run AI: the case brief is generated by a GET. */
const AI_READS = [/^\/api(?:\/v1)?\/my-cases\/[^/]+\/export$/];

/** An account's free credit (User.freeCreditUsd) and what it has spent of it, or null for an
 * account with no credit (created before it existed), which is never limited. */
export async function freeCreditState(userId: string) {
  const creditUsd = await AuthRepo.findFreeCredit(userId);
  if (creditUsd === null) return null;
  const spentUsd = await LlmUsageSvc.chatWonderSpendUsd(userId);
  return { creditUsd, spentUsd, spent: spentUsd >= creditUsd };
}

/** Once an account has spent its free credit (OpenAI usage through Chat Wonder), it starts no new
 * work: every write and the case brief answer 403 FREE_CREDIT_SPENT, reads still pass, and
 * ALWAYS_OPEN stays open. Until subscription tiers exist nothing lifts this; being on a tier will.
 * Spend is only known after a call ends, so the request that crosses the line still finishes.
 * Mounted ahead of every router, so it reads the token itself; a request without a valid one
 * passes through for the router's own checks to deal with. */
export async function freeCreditLimit(req: Request, _res: Response, next: NextFunction) {
  try {
    const path = `${req.baseUrl}${req.path}`.replace(/\/$/, "");
    const aiRead = AI_READS.some((r) => r.test(path));
    if ((req.method === "GET" || req.method === "HEAD" || req.method === "OPTIONS") && !aiRead) return next();
    if (ALWAYS_OPEN.test(path) || CLIENT_APP.test(path)) return next();
    const token = req.headers.authorization?.split(" ")[1];
    if (!token) return next();
    let userId: string | undefined;
    try {
      userId = (jwt.verify(token, ACCESS_TOKEN_SECRET) as { userId?: string }).userId;
    } catch {
      return next();
    }
    if (userId && (await freeCreditState(userId))?.spent) {
      throw new HttpError("You've used your free AI credit. Choose a plan to keep going.", 403, "FREE_CREDIT_SPENT");
    }
    next();
  } catch (err) {
    next(err);
  }
}
